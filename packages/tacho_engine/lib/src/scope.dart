/// Тип транспорта. Лимиты 561/2006 от него не зависят — только то, в каких
/// перевозках они действуют (ст. 2(1) в ред. Регламента 2020/1054).
enum VehicleType {
  /// Грузовик тяжелее 3,5 т вместе с прицепом или автобус: правила
  /// действуют в любой перевозке, и внутри страны (ст. 2(1)(a), (b)).
  truckOrBus,

  /// Фургон тяжелее 2,5 т и не тяжелее 3,5 т вместе с прицепом: с 01.07.2026
  /// правила действуют в международной перевозке грузов и каботаже
  /// (ст. 2(1)(aa)).
  van,
}

/// Кто и зачем везёт груз на фургоне — от этого зависят исключения ст. 3.
enum VanCarriage {
  /// По найму или за вознаграждение: курьер, перевозчик.
  hireOrReward,

  /// Своя перевозка: груз, материалы или инструмент своей фирмы или самого
  /// водителя.
  ownAccount,

  /// Некоммерческая перевозка (ст. 4(r)): без оплаты, без дохода и не
  /// связана с работой — например, свой переезд.
  nonCommercial,
}

/// Действуют ли правила 561/2006 в рейсе фургона и по какой статье.
enum VanRules {
  /// Действуют: тахограф, карта водителя и все лимиты — как у грузовика.
  applies('2(1)(aa)'),

  /// Рейс до 01.07.2026: фургоны в регламент ещё не входили.
  notYet('2(1)(aa)'),

  /// Перевозка внутри одной страны, не каботаж: регламент фургон не
  /// касается, могут действовать правила страны.
  domestic('2(1)(aa)'),

  /// Своя перевозка, и вождение — не основная работа водителя.
  ownAccountExempt('3(ha)'),

  /// Некоммерческая перевозка.
  nonCommercialExempt('3(h)');

  new(this.article);

  /// Статья Регламента 561/2006 в ред. 2020/1054.
  final String article;
}

/// Правила 561/2006 для фургонов 2,5–3,5 т — с этого момента (ст. 2(1)(aa)).
final DateTime vanRulesFrom = DateTime.utc(2026, 7); // 01.07.2026

/// Действуют ли правила 561/2006 в рейсе фургона 2,5–3,5 т вместе с
/// прицепом ([VehicleType.van]).
///
/// [at] — момент рейса, UTC. [crossBorder] — международная перевозка или
/// каботаж (перевозка внутри другой страны ЕС). [drivingMainActivity] —
/// вождение — основная работа водителя.
///
/// Исключение ст. 3(aa) (материалы и инструмент для своей работы, изделия
/// ремесленника в радиусе 100 км) требует того же, что 3(ha): перевозка не
/// по найму и вождение — не основная работа. Для фургона оно ничего не
/// добавляет. Исключения по назначению машины (аварийные службы, армия,
/// дорожные испытания и другие пункты ст. 3) касаются любого транспорта —
/// движок о них не спрашивает. `docs/domain/eu-561-rules.md`, «Фургоны».
VanRules vanRules({
  required DateTime at,
  required bool crossBorder,
  required VanCarriage carriage,
  required bool drivingMainActivity,
}) {
  if (!at.isUtc) throw ArgumentError.value(at, 'at', 'должно быть в UTC');
  if (at.isBefore(vanRulesFrom)) return VanRules.notYet;
  if (!crossBorder) return VanRules.domestic;
  return switch (carriage) {
    VanCarriage.nonCommercial => VanRules.nonCommercialExempt,
    VanCarriage.ownAccount when !drivingMainActivity =>
      VanRules.ownAccountExempt,
    _ => VanRules.applies,
  };
}
