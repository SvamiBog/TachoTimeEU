/// Режим водителя — соответствует символам тахографа.
enum DriverMode {
  /// Вождение (руль).
  driving,

  /// Другая работа (молотки).
  otherWork,

  /// Готовность (квадрат с диагональю).
  availability,

  /// Отдых или перерыв (кровать).
  rest;

  /// Рабочее время по Директиве 2002/15/ЕС: вождение и другая работа.
  ///
  /// Не использовать для лимита рабочего дня 13/15 ч: это окно между
  /// суточными отдыхами, в него входит всё, кроме отдыха (в том числе
  /// готовность). Для него — [isRest].
  bool get isWorkingTime => this == driving || this == otherWork;

  /// Отдых или перерыв: только он прерывает непрерывное вождение и смену.
  bool get isRest => this == rest;
}
