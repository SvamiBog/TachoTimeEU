/// Режим водителя — соответствует символам тахографа.
enum DriverMode {
  /// Вождение (руль).
  driving,

  /// Другая работа (молотки).
  otherWork,

  /// Готовность (квадрат с диагональю).
  availability,

  /// Отдых или перерыв (кровать).
  rest;

  /// Считается ли режим рабочим временем для лимитов рабочего дня.
  bool get isWork => this == driving || this == otherWork;
}
